// Regenerate the committed database schema snapshots and Liam ERDs.
//
//   node scripts/quality/generate-db-schema.mjs           regenerate docs/db/**
//   node scripts/quality/generate-db-schema.mjs --check    regenerate, then fail if docs/db/** changed (CI)
//   node scripts/quality/generate-db-schema.mjs --clean    force a disposable postgres container
//   node scripts/quality/generate-db-schema.mjs --reuse    force the configured postgres (DB_SCHEMA_PG_* / dev stack)
//
// Set SKIP_DB_SCHEMA=1 to skip entirely (or commit with --no-verify).
//
// See docs/db/README.md.

import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import process from 'node:process'

import { runCapture } from './run.mjs'
import { DATABASES, DOCS_DIR, SPA_DIR } from './db-schema/config.mjs'
import { acquirePostgres, resetDatabase } from './db-schema/postgres.mjs'
import { applyMigrations } from './db-schema/migrate.mjs'
import { dumpSchema } from './db-schema/dump.mjs'
import { buildErd } from './db-schema/liam.mjs'

const args = new Set(process.argv.slice(2))
const check = args.has('--check')
const pgMode = args.has('--clean')
  ? 'clean'
  : args.has('--reuse')
    ? 'reuse'
    : check
      ? 'clean'
      : 'reuse'

const yellow = (text) => `[33m${text}[0m`

if (process.env.SKIP_DB_SCHEMA === '1') {
  console.log('SKIP_DB_SCHEMA=1 — skipping database schema generation.')
  process.exit(0)
}

function databaseReadme(db) {
  return `# ${db.name} database schema

Generated by \`npm run quality:db-schema\` — **do not edit by hand.**

- \`schema.sql\` — \`pg_dump --schema-only\` of every committed migration applied to an empty database.
- \`schema.json\` — the same schema parsed by the Liam ERD CLI.

## Interactive ERD

| Environment | URL |
| --- | --- |
| Development | <${db.urls.dev}> |
| Production | <${db.urls.prod}> |

The single-page app is built from \`schema.sql\` into \`${SPA_DIR}/${db.name}/\` (git-ignored) and
served by the gateway. Run \`npm run erd:build\` in \`dashboard/\` to rebuild it locally.
`
}

function indexReadme() {
  const rows = DATABASES.map(
    (db) => `| \`${db.name}\` | [schema.sql](${db.name}/schema.sql) | [dev](${db.urls.dev}) · [prod](${db.urls.prod}) |`,
  ).join('\n')
  return `# Database schemas

Committed snapshots of every application database, plus an interactive ERD per database built
with [Liam](https://github.com/liam-hq/liam).

| Database | Snapshot | Interactive ERD |
| --- | --- | --- |
${rows}

## How it is kept current

\`scripts/quality/generate-db-schema.mjs\` applies every committed migration to an empty
PostgreSQL database, exports the schema with \`pg_dump\`, and runs the Liam CLI. The \`pre-commit\`
hook runs it whenever a migration changes and stages the result; CI re-runs it against a
disposable database and fails on drift.

\`\`\`sh
npm run quality:db-schema              # uses the running dev postgres
npm run quality:db-schema -- --clean   # uses a disposable container
\`\`\`
`
}

const acquired = await acquirePostgres(pgMode)

if (!acquired) {
  const message =
    'dev PostgreSQL is not reachable — start the dev stack or run `npm run quality:db-schema -- --clean`.'
  if (check) {
    console.error(yellow(message))
    process.exit(1)
  }
  console.warn(yellow(`Skipping database schema generation: ${message}`))
  process.exit(0)
}

const { server, dispose } = acquired
const spaRoot = check ? mkdtempSync(join(tmpdir(), 'crm-db-erd-')) : SPA_DIR

try {
  for (const db of DATABASES) {
    console.log(`• ${db.name}: reset → migrate → dump → erd`)
    resetDatabase(server, db.database)
    applyMigrations(db, server)

    const dir = join(DOCS_DIR, db.name)
    mkdirSync(dir, { recursive: true })
    const sqlPath = join(dir, 'schema.sql')
    writeFileSync(sqlPath, dumpSchema(server, db.database))
    writeFileSync(join(dir, 'schema.json'), buildErd(sqlPath, join(spaRoot, db.name)))
    writeFileSync(join(dir, 'README.md'), databaseReadme(db))
  }
  writeFileSync(join(DOCS_DIR, 'README.md'), indexReadme())
} finally {
  dispose()
  if (check) rmSync(spaRoot, { recursive: true, force: true })
}

if (check) {
  // `git diff` catches changes to tracked files; the porcelain scan catches a
  // schema that was never committed at all.
  const changed = runCapture('git', ['diff', '--exit-code', '--stat', '--', DOCS_DIR], { capture: true })
  const untracked = runCapture(
    'git',
    ['ls-files', '--others', '--exclude-standard', '--', DOCS_DIR],
    { capture: true },
  )
  const stale = [
    ...changed.stdout.split('\n').filter((line) => line.trim()),
    ...untracked.stdout.split('\n').filter((line) => line.trim()).map((path) => `new: ${path}`),
  ]
  if (changed.status !== 0 || stale.length) {
    console.error(yellow('\nCommitted database schema is stale:'))
    console.error(stale.map((line) => `  ${line}`).join('\n'))
    console.error('\nRun `npm run quality:db-schema` and commit `docs/db/`.\n')
    process.exit(1)
  }
  console.log('\nDatabase schema is up to date.')
}
